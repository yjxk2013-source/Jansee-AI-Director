/**
 * 本地引擎检索优先层：变体判定第一权威（与 LLM 解耦）。
 * 文案命中强信号 → 直接返回对应类型（确定性）；
 * 命中类型已被占用 → 排重优先，本地轮询剩余类型（不调 LLM）；
 * 未命中任何信号 → 返回 ''（交由 LLM 按类型表兜底自主判定长尾开放场景）。
 * @param {string} inputText  用户输入的商品/门店文案（信号匹配的输入）
 * @param {string} mode       'sell' | 'local'；其它模式（如 personal）无变体体系
 * @param {string[]} usedTypes 已用过的变体类型（命中类型已被占用时在剩余类型里轮询）
 * @returns {string} 命中的类型名，未命中返回空串
 */
export function decideVariantLocal(inputText, mode = 'sell', usedTypes = []) {
  if (mode !== 'sell' && mode !== 'local') return '';
  const txt = String(inputText || '').trim();
  if (!txt) return '';
  const used = new Set((Array.isArray(usedTypes) ? usedTypes : []).map((s) => String(s).trim()).filter(Boolean));
  const rules = mode === 'local' ? LOCAL_SIGNAL_RULES : SELL_SIGNAL_RULES;
  const typeNames = mode === 'local' ? LOCAL_VARIANT_TYPES : SELL_VARIANT_TYPES;
  for (const r of rules) {
    if (r.re.test(txt)) {
      if (!used.has(r.type)) return r.type;
      // 命中但该类型已被占用 → 排重优先，本地轮询剩余类型（不再回退 LLM）
      const rest = typeNames.filter((t) => !used.has(t));
      if (rest.length) return rest[0];
      return r.type; // 全部用完 → 允许复用信号命中类型
    }
  }
  return ''; // 未命中任何强信号 → 交由 LLM 兜底
}
